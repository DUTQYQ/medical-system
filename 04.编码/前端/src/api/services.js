import request from '@/utils/request'
import { asList } from '@/utils/format'
export const listServiceProfiles = async () => asList(await request.get('/services/profiles'))
export const getServiceCatalog = async () => asList(await request.get('/services/catalog'))
export const createServiceCategory = body => request.post('/services/catalog', body)
export const saveServiceCategory = (category, body) => request.put(`/services/catalog/${category}`, body)
export const listServiceRequests = params => request.get('/services/requests', { params })
export const createServiceRequest = body => request.post('/services/requests', body)
export const createServiceCall = body => request.post('/services/calls', body)
export const getServiceRequest = id => request.get(`/services/requests/${id}`)
export const transitionServiceRequest = (id, body) => request.post(`/services/requests/${id}/transition`, body)
export const listServiceActivities = async () => asList(await request.get('/services/activities'))
export const createServiceActivity = body => request.post('/services/activities', body)
export const transitionServiceActivity = (id, status) => request.post(`/services/activities/${id}/transition`, {status})
export const registerServiceActivity = (id, profile_id) => request.post(`/services/activities/${id}/register`, { profile_id })
export const listActivityRegistrations = async id => asList(await request.get(`/services/activities/${id}/registrations`))
export const transitionActivityRegistration = (id, status) => request.post(`/services/registrations/${id}/transition`, { status })
export const listServiceEquipment = async () => asList(await request.get('/services/equipment'))
export const createServiceEquipment = body => request.post('/services/equipment', body)
export const updateServiceEquipment = (id, body) => request.put(`/services/equipment/${id}`, body)
export const requestServiceEquipment = (id, body) => request.post(`/services/equipment/${id}/request`, body)
export const listServiceLoans = async params => asList(await request.get('/services/loans', { params }))
export const returnServiceLoan = (id, body) => request.post(`/services/loans/${id}/return`, body)
export const listServiceNotifications = () => request.get('/services/notifications')
export const readServiceNotification = id => request.post(`/services/notifications/${id}/read`)
export const getServiceDashboard = () => request.get('/services/dashboard')
export const getServiceSettings = () => request.get('/services/settings')
export const saveServiceSettings = body => request.put('/services/settings',body)
